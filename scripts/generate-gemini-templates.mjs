import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
export const TEMPLATES_DIR = join(ROOT, 'templates');
export const OUTPUT_PATH = join(ROOT, 'src', 'geminiTemplates.ts');
export const SUPPORTED_SIZES = new Set([48, 56, 96]);

function assertRgbTuple(value, field, id) {
  if (!Array.isArray(value) || value.length !== 3) {
    throw new Error(`${id}: ${field} must be an RGB tuple`);
  }
  for (const channel of value) {
    if (!Number.isFinite(channel) || channel < 0 || channel > 255) {
      throw new Error(`${id}: ${field} values must be finite numbers in [0, 255]`);
    }
  }
}

export function validateTemplateAsset(template, filename = '<memory>') {
  const id = typeof template.id === 'string' && template.id ? template.id : filename;
  if (typeof template.id !== 'string' || template.id.length === 0) {
    throw new Error(`${filename}: id must be a non-empty string`);
  }
  if (!SUPPORTED_SIZES.has(template.width) || template.height !== template.width) {
    throw new Error(`${id}: width/height must be one of 48x48, 56x56, or 96x96`);
  }
  if (!Array.isArray(template.alpha)) {
    throw new Error(`${id}: alpha must be an array`);
  }
  const expectedLength = template.width * template.height;
  if (template.alpha.length !== expectedLength) {
    throw new Error(`${id}: alpha length ${template.alpha.length} must equal width * height ${expectedLength}`);
  }
  for (const alpha of template.alpha) {
    if (!Number.isFinite(alpha) || alpha < 0 || alpha > 1) {
      throw new Error(`${id}: alpha values must be finite numbers in [0, 1]`);
    }
  }
  assertRgbTuple(template.color, 'color', id);
  if (template.blendMode !== 'normal-alpha') {
    throw new Error(`${id}: blendMode must be normal-alpha`);
  }
  if (typeof template.version !== 'string' || template.version.length === 0) {
    throw new Error(`${id}: version must be a non-empty string`);
  }
  return template;
}

export async function readTemplateAssets() {
  const files = (await readdir(TEMPLATES_DIR))
    .filter((file) => file.endsWith('.json'))
    .sort();
  if (files.length === 0) {
    throw new Error(`no template JSON files found in ${TEMPLATES_DIR}`);
  }
  const templates = [];
  for (const file of files) {
    const parsed = JSON.parse(await readFile(join(TEMPLATES_DIR, file), 'utf8'));
    templates.push(validateTemplateAsset(parsed, file));
  }
  templates.sort((a, b) => a.width - b.width || a.id.localeCompare(b.id));
  return templates;
}

function constantName(template) {
  return template.id.toUpperCase().replaceAll('-', '_');
}

function alphaLiteral(alpha) {
  return `[${alpha.map((value) => Number(value).toString()).join(',')}]`;
}

function optionalProperty(template, key) {
  return template[key] === undefined ? '' : `,\n      ${key}: ${JSON.stringify(template[key])}`;
}

export function renderGeminiTemplates(templates) {
  const arrays = templates
    .map((template) => `const ${constantName(template)}_ALPHA: readonly number[] = ${alphaLiteral(template.alpha)};`)
    .join('\n\n');

  const cases = templates
    .map((template) => `    createTemplate({
      id: ${JSON.stringify(template.id)},
      width: ${template.width},
      height: ${template.height},
      alpha: ${constantName(template)}_ALPHA,
      color: ${JSON.stringify(template.color)} as [number, number, number],
      blendMode: ${JSON.stringify(template.blendMode)},
      version: ${JSON.stringify(template.version)}${optionalProperty(template, 'source')}${optionalProperty(template, 'provider')}${optionalProperty(template, 'calibratedAt')}${optionalProperty(template, 'notes')}
    })`)
    .join(',\n');

  return `// Generated by scripts/generate-gemini-templates.mjs from templates/*.json.
// Do not edit this file by hand.

import type { WatermarkTemplate } from './types.js';

interface GeneratedTemplateAsset {
  id: string;
  width: 48 | 56 | 96;
  height: 48 | 56 | 96;
  alpha: readonly number[];
  color: [number, number, number];
  blendMode: 'normal-alpha';
  version: string;
  source?: string;
  provider?: string;
  calibratedAt?: string;
  notes?: string;
}

${arrays}

function createTemplate(asset: GeneratedTemplateAsset): WatermarkTemplate {
  return {
    id: asset.id,
    width: asset.width,
    height: asset.height,
    alpha: Float32Array.from(asset.alpha),
    color: asset.color,
    blendMode: asset.blendMode,
    version: asset.version,
    source: asset.source,
    provider: asset.provider,
    calibratedAt: asset.calibratedAt,
    notes: asset.notes
  };
}

export function createRealGeminiTemplates(): WatermarkTemplate[] {
  return [
${cases}
  ];
}
`;
}

export async function generateGeminiTemplates() {
  const templates = await readTemplateAssets();
  const output = renderGeminiTemplates(templates);
  await writeFile(OUTPUT_PATH, output);
  return output;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateGeminiTemplates();
}
